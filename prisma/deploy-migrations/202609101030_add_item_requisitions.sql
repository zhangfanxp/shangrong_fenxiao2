CREATE TABLE `ItemRequisitionSequence` (
  `dateKey` VARCHAR(8) NOT NULL,
  `nextValue` INTEGER NOT NULL DEFAULT 1,
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`dateKey`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `ItemRequisition` (
  `id` VARCHAR(191) NOT NULL,
  `requisitionNo` VARCHAR(12) NOT NULL,
  `requestId` VARCHAR(36) NOT NULL,
  `requisitionedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `personnelId` VARCHAR(191) NOT NULL,
  `personnelNameSnapshot` VARCHAR(50) NOT NULL,
  `personnelBelongingSnapshot` VARCHAR(50) NOT NULL,
  `departmentStoreSnapshot` VARCHAR(100) NULL,
  `itemId` VARCHAR(191) NOT NULL,
  `itemRecordNoSnapshot` VARCHAR(12) NOT NULL,
  `itemNameSnapshot` VARCHAR(30) NOT NULL,
  `itemTypeCodeSnapshot` VARCHAR(100) NOT NULL,
  `itemTypeNameSnapshot` VARCHAR(100) NOT NULL,
  `specificationSnapshot` VARCHAR(50) NULL,
  `unitSnapshot` VARCHAR(5) NOT NULL,
  `manageStockSnapshot` ENUM('MANAGED', 'UNMANAGED') NOT NULL,
  `quantity` INTEGER UNSIGNED NOT NULL,
  `remark` VARCHAR(100) NULL,
  `status` ENUM('NORMAL', 'REVOKED') NOT NULL DEFAULT 'NORMAL',
  `version` INTEGER NOT NULL DEFAULT 1,
  `createdByUserId` VARCHAR(191) NULL,
  `createdByUsername` VARCHAR(30) NOT NULL,
  `createdByNameSnapshot` VARCHAR(50) NOT NULL,
  `updatedByUserId` VARCHAR(191) NULL,
  `updatedByNameSnapshot` VARCHAR(50) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  UNIQUE INDEX `ItemRequisition_requisitionNo_key` (`requisitionNo`),
  UNIQUE INDEX `ItemRequisition_requestId_key` (`requestId`),
  INDEX `ItemRequisition_requisitionedAt_id_idx` (`requisitionedAt`, `id`),
  INDEX `ItemRequisition_personnelId_requisitionedAt_idx` (`personnelId`, `requisitionedAt`),
  INDEX `ItemRequisition_itemId_requisitionedAt_idx` (`itemId`, `requisitionedAt`),
  INDEX `ItemRequisition_itemNameSnapshot_idx` (`itemNameSnapshot`),
  INDEX `ItemRequisition_personnelNameSnapshot_idx` (`personnelNameSnapshot`),
  INDEX `ItemRequisition_createdByUserId_idx` (`createdByUserId`),
  INDEX `ItemRequisition_updatedByUserId_idx` (`updatedByUserId`),
  PRIMARY KEY (`id`),
  CONSTRAINT `ItemRequisition_personnelId_fkey` FOREIGN KEY (`personnelId`) REFERENCES `Personnel` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `ItemRequisition_itemId_fkey` FOREIGN KEY (`itemId`) REFERENCES `InventoryItem` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `ItemRequisition_createdByUserId_fkey` FOREIGN KEY (`createdByUserId`) REFERENCES `User` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `ItemRequisition_updatedByUserId_fkey` FOREIGN KEY (`updatedByUserId`) REFERENCES `User` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `ItemRequisition_quantity_check` CHECK (`quantity` > 0)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
